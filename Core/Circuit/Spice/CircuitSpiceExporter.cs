using System.Globalization;
using System.Text;

namespace CircuitModuleDesigner.Core.Circuit.Spice;

/// <summary>Exports a basic Berkeley SPICE netlist intended for Multisim .cir import.</summary>
public sealed class CircuitSpiceExporter : ICircuitSpiceExporter
{
    public string Export(CircuitGraph graph, CircuitSpiceExportOptions options)
    {
        ArgumentNullException.ThrowIfNull(graph); ArgumentNullException.ThrowIfNull(options);
        if (options.StartFrequencyHz <= 0 || options.StopFrequencyHz <= options.StartFrequencyHz) throw new ArgumentOutOfRangeException(nameof(options));
        var text = new StringBuilder();
        text.AppendLine(SanitizeTitle(options.Title));
        text.AppendLine("* Generated by Circuit Module Designer");
        text.AppendLine("* Multisim-compatible basic Berkeley SPICE netlist");
        text.AppendLine("* Abstract op-amps are exported as finite-gain VCVS elements.");
        text.AppendLine();

        if (options.SourceResistanceOhm is > 0)
        {
            text.AppendLine("* Thevenin input source: ideal voltage source followed by series source resistance Rs");
            text.AppendLine("V_INPUT N_SOURCE 0 DC 0 AC 1");
            text.AppendLine($"R_SOURCE N_SOURCE VIN {Number(options.SourceResistanceOhm.Value)}");
        }
        else text.AppendLine("V_INPUT VIN 0 DC 0 AC 1");

        foreach (var component in graph.Components.OrderBy(ComponentOrder).ThenBy(component => component.Reference, NaturalReferenceComparer.Instance))
        {
            if (component.Type == ComponentType.OpAmp)
            {
                var output = Net(graph, component, "OUT"); var positive = Net(graph, component, "IN+"); var negative = Net(graph, component, "IN-");
                text.AppendLine($"E_{component.Reference} {output} 0 {positive} {negative} {Number(options.OpAmpOpenLoopGain)}");
                continue;
            }
            var first = Net(graph, component, "1"); var second = Net(graph, component, "2");
            var value = component.Type switch
            {
                ComponentType.Resistor => component.Parameters.GetRequiredValue(ComponentParameterNames.ResistanceOhm),
                ComponentType.Capacitor => component.Parameters.GetRequiredValue(ComponentParameterNames.CapacitanceFarad),
                ComponentType.Inductor => component.Parameters.GetRequiredValue(ComponentParameterNames.InductanceHenry),
                _ => throw new NotSupportedException($"No SPICE export mapping exists for {component.Type}.")
            };
            text.AppendLine($"{component.Reference} {first} {second} {Number(value)}");
        }

        if (options.LoadResistanceOhm is > 0)
        {
            text.AppendLine("* Shunt load termination RL from VOUT to ground");
            text.AppendLine($"R_LOAD VOUT 0 {Number(options.LoadResistanceOhm.Value)}");
        }
        else text.AppendLine("R_OUTPUT_LOAD VOUT 0 1e9");
        text.AppendLine();
        text.AppendLine($".AC DEC {options.PointsPerDecade} {Number(options.StartFrequencyHz)} {Number(options.StopFrequencyHz)}");
        text.AppendLine(".PRINT AC VM(VOUT) VP(VOUT)");
        text.AppendLine(".END");
        return text.ToString();
    }

    private static string Net(CircuitGraph graph, CircuitComponent component, string pinName)
    {
        var net = graph.GetNetForPin(component.GetPin(pinName)) ?? throw new InvalidOperationException($"{component.Reference}.{pinName} is not connected.");
        return net.Name.Equals("GND", StringComparison.OrdinalIgnoreCase) ? "0" : SanitizeNode(net.Name);
    }

    private static int ComponentOrder(CircuitComponent component) => component.Type switch
    {
        ComponentType.Resistor => 0, ComponentType.Capacitor => 1, ComponentType.Inductor => 2, ComponentType.OpAmp => 3, _ => 9
    };
    private static string Number(double value) => value.ToString("0.###############e+0", CultureInfo.InvariantCulture);
    private static string SanitizeTitle(string title) => string.IsNullOrWhiteSpace(title) ? "Circuit Module Designer Filter" : title.Replace('\r', ' ').Replace('\n', ' ');
    private static string SanitizeNode(string name)
    {
        var value = new string(name.Select(character => char.IsLetterOrDigit(character) || character == '_' ? character : '_').ToArray());
        return string.IsNullOrEmpty(value) ? "N_UNNAMED" : value;
    }

    private sealed class NaturalReferenceComparer : IComparer<string>
    {
        public static NaturalReferenceComparer Instance { get; } = new();
        public int Compare(string? first, string? second)
        {
            if (ReferenceEquals(first, second)) return 0; if (first == null) return -1; if (second == null) return 1;
            var firstPrefix = new string(first.TakeWhile(char.IsLetter).ToArray()); var secondPrefix = new string(second.TakeWhile(char.IsLetter).ToArray());
            var prefix = string.Compare(firstPrefix, secondPrefix, StringComparison.OrdinalIgnoreCase); if (prefix != 0) return prefix;
            return int.TryParse(first[firstPrefix.Length..], out var firstNumber) && int.TryParse(second[secondPrefix.Length..], out var secondNumber)
                ? firstNumber.CompareTo(secondNumber) : string.Compare(first, second, StringComparison.OrdinalIgnoreCase);
        }
    }
}
