namespace CircuitModuleDesigner.Core.Circuit.Spice;

/// <summary>Maps CircuitGraph components to common SPICE elements. It performs no circuit synthesis.</summary>
public sealed class CircuitGraphSpiceSerializer
{
    public SpiceNetlistDocument Serialize(CircuitGraph graph, CircuitSpiceExportOptions options, SpiceNetlistDialect? dialectOverride = null)
    {
        ArgumentNullException.ThrowIfNull(graph);
        ArgumentNullException.ThrowIfNull(options);
        Validate(options);
        ValidateNodeMappings(graph);

        var elements = new List<string>();
        foreach (var source in options.Sources) elements.Add(Source(source));
        if (options.SourceResistanceOhm is > 0)
            elements.Add($"R_SOURCE {SpiceText.Node("VSRC")} {SpiceText.Node("VIN")} {SpiceText.Number(options.SourceResistanceOhm.Value)}");

        foreach (var component in graph.Components.OrderBy(ComponentOrder).ThenBy(component => component.Reference, NaturalReferenceComparer.Instance))
            elements.Add(Component(graph, component, options));

        if (options.LoadResistanceOhm is > 0)
            elements.Add($"R_LOAD {SpiceText.Node("VOUT")} 0 {SpiceText.Number(options.LoadResistanceOhm.Value)}");
        else if (options.HighImpedanceOutputLoadOhm is > 0)
            elements.Add($"R_OUTPUT_LOAD {SpiceText.Node("VOUT")} 0 {SpiceText.Number(options.HighImpedanceOutputLoadOhm.Value)}");
        var duplicateElement = elements.Select(line => line.Split(' ', 2)[0]).GroupBy(name => name, StringComparer.OrdinalIgnoreCase).FirstOrDefault(group => group.Count() > 1);
        if (duplicateElement is not null) throw new InvalidOperationException($"SPICE element-name collision after identifier normalization: {duplicateElement.Key}.");

        var modelLines = new List<string>();
        foreach (var include in options.LibraryIncludes) modelLines.Add($".INCLUDE {SpiceText.QuotePath(include)}");
        foreach (var library in options.Libraries)
            modelLines.Add($".LIB {SpiceText.QuotePath(library.Path)}{(string.IsNullOrWhiteSpace(library.EntryName) ? string.Empty : " " + SpiceText.Identifier(library.EntryName, "ENTRY"))}");
        foreach (var parameter in options.Parameters.OrderBy(pair => pair.Key, StringComparer.OrdinalIgnoreCase))
            modelLines.Add($".PARAM {SpiceText.Identifier(parameter.Key, "P") }={SpiceText.Number(parameter.Value)}");
        if (options.DiodeModel is { } diode && graph.Components.Any(component => component.Type == ComponentType.Diode))
        {
            var rs = diode.SeriesResistanceOhm is > 0 ? $" RS={SpiceText.Number(diode.SeriesResistanceOhm.Value)}" : string.Empty;
            modelLines.Add($".MODEL {SpiceText.Identifier(diode.Name, "CMD_DIODE")} D(IS={SpiceText.Number(diode.SaturationCurrentAmpere)} N={SpiceText.Number(diode.EmissionCoefficient)}{rs})");
        }
        if (options.OpAmpMode == SpiceOpAmpExportMode.ExternalSubcircuit && options.OpAmpSubcircuit is { } subcircuit)
        {
            if (!string.IsNullOrWhiteSpace(subcircuit.IncludePath)) modelLines.Add($".INCLUDE {SpiceText.QuotePath(subcircuit.IncludePath)}");
            if (subcircuit.EmbeddedBodyLines is { Count: > 0 })
            {
                modelLines.Add($".SUBCKT {SpiceText.Identifier(subcircuit.Name, "CMD_OPAMP")} {string.Join(' ', subcircuit.PinOrder.Select(pin => SpiceText.Identifier(pin, "P")))}");
                modelLines.AddRange(subcircuit.EmbeddedBodyLines);
                modelLines.Add($".ENDS {SpiceText.Identifier(subcircuit.Name, "CMD_OPAMP")}");
            }
        }
        if (options.TemperatureCelsius is { } temperature) modelLines.Add($".TEMP {SpiceText.Number(temperature)}");

        var analyses = options.Analyses.Select(Analysis).ToArray();
        var dialectKind = dialectOverride ?? options.Dialect;
        // LTspice has no .PRINT directive; numeric output is obtained from the
        // waveform viewer or .MEAS statements. Berkeley/Multisim keep .PRINT so
        // batch text output still works there.
        var outputs = dialectKind == SpiceNetlistDialect.Ltspice
            ? []
            : options.OutputExpressions.Select(expression => $".PRINT {AnalysisDomain(options.Analyses)} {expression}").ToArray();
        var dialect = dialectKind switch
        {
            SpiceNetlistDialect.Ltspice => "LTspice-compatible text netlist (.cir/.net; not .asc)",
            SpiceNetlistDialect.Multisim => "Multisim-compatible Berkeley SPICE text netlist",
            _ => "Generic Berkeley SPICE text netlist"
        };
        var comments = new List<string> { "Generated by Circuit Module Designer", dialect };
        if (dialectKind == SpiceNetlistDialect.Ltspice && options.OutputExpressions.Count > 0)
            comments.Add("LTspice does not support .PRINT; use the waveform viewer or .MEAS statements. The analysis directive and nodes are exported.");
        comments.Add(options.OpAmpMode switch
        {
            SpiceOpAmpExportMode.FiniteGainVcvs => "Abstract op-amps use finite-gain E-source (VCVS) models; supply pins do not limit output swing.",
            SpiceOpAmpExportMode.ExternalSubcircuit => "Abstract op-amps call the explicitly configured external/embedded subcircuit.",
            _ => "Abstract op-amp export is disabled."
        });
        if (options.DiodeModel is not null && graph.Components.Any(component => component.Type == ComponentType.Diode))
            comments.Add("Diodes reference the explicit exported .MODEL; no simulator-default diode is assumed.");
        if (options.IdealDiodeModel is { } idealDiode && graph.Components.Any(component => component.Type == ComponentType.Diode))
            comments.Add($"Diodes use behavioral ideal-switch branches (Ron={SpiceText.Number(idealDiode.OnResistanceOhm)} ohm, Roff={SpiceText.Number(idealDiode.OffResistanceOhm)} ohm) matching the verified conducting/blocking state model.");
        comments.AddRange(options.AdditionalComments.Where(comment => !string.IsNullOrWhiteSpace(comment)));
        return new(SpiceText.Title(options.Title), comments, elements, modelLines, analyses, outputs);
    }

    private static string Component(CircuitGraph graph, CircuitComponent component, CircuitSpiceExportOptions options) => component.Type switch
    {
        ComponentType.Resistor => Passive(graph, component, "R", ComponentParameterNames.ResistanceOhm),
        ComponentType.Capacitor => Passive(graph, component, "C", ComponentParameterNames.CapacitanceFarad),
        ComponentType.Inductor => Passive(graph, component, "L", ComponentParameterNames.InductanceHenry),
        ComponentType.OpAmp => OpAmp(graph, component, options),
        ComponentType.Diode => Diode(graph, component, options),
        ComponentType.Comparator => Comparator(graph, component),
        ComponentType.LogicGate => LogicGate(graph, component),
        _ => throw new NotSupportedException($"No SPICE export mapping exists for {component.Type}.")
    };

    private static string Comparator(CircuitGraph graph, CircuitComponent component)
    {
        var behavior = (ComparatorOutputBehavior)(int)component.Parameters.GetRequiredValue(ComponentParameterNames.OutputBehavior);
        if (behavior == ComparatorOutputBehavior.OpenCollector)
            throw new NotSupportedException("Open-collector comparator SPICE export requires an explicit pull-up/load model; the static CircuitGraph is retained but is not exported as push-pull.");
        var high = component.Parameters.GetRequiredValue(ComponentParameterNames.OutputHighVoltage);
        var low = component.Parameters.GetRequiredValue(ComponentParameterNames.OutputLowVoltage);
        return $"{ElementName(component.Reference, "B")} {Net(graph, component, "OUT")} 0 V=IF(V({Net(graph, component, "IN+")})>V({Net(graph, component, "IN-")}),{SpiceText.Number(high)},{SpiceText.Number(low)})";
    }

    private static string LogicGate(CircuitGraph graph, CircuitComponent component)
    {
        var high = SpiceText.Number(component.Parameters.GetRequiredValue(ComponentParameterNames.OutputHighVoltage));
        var low = SpiceText.Number(component.Parameters.GetRequiredValue(ComponentParameterNames.OutputLowVoltage));
        var a = $"V({Net(graph, component, "A")})"; var b = $"V({Net(graph, component, "B")})";
        var midpoint = SpiceText.Number((component.Parameters.GetRequiredValue(ComponentParameterNames.OutputHighVoltage) + component.Parameters.GetRequiredValue(ComponentParameterNames.OutputLowVoltage)) / 2);
        var condition = (LogicGateFunction)(int)component.Parameters.GetRequiredValue(ComponentParameterNames.LogicFunction) switch
        {
            LogicGateFunction.And => $"({a}>{midpoint})&&({b}>{midpoint})",
            LogicGateFunction.Or => $"({a}>{midpoint})||({b}>{midpoint})",
            LogicGateFunction.NotAAndB => $"({a}<{midpoint})&&({b}>{midpoint})",
            LogicGateFunction.AOrNotB => $"({a}>{midpoint})||({b}<{midpoint})",
            _ => throw new NotSupportedException("Unsupported logic function.")
        };
        return $"{ElementName(component.Reference, "B")} {Net(graph, component, "OUT")} 0 V=IF({condition},{high},{low})";
    }

    private static string Passive(CircuitGraph graph, CircuitComponent component, string prefix, string parameter)
    {
        var value = component.Parameters.GetRequiredValue(parameter);
        if (!(value > 0)) throw new InvalidOperationException($"{component.Reference} must have a positive value for SPICE export.");
        return $"{ElementName(component.Reference, prefix)} {Net(graph, component, "1")} {Net(graph, component, "2")} {SpiceText.Number(value)}";
    }

    private static string Diode(CircuitGraph graph, CircuitComponent component, CircuitSpiceExportOptions options)
    {
        if (options.IdealDiodeModel is { } ideal)
        {
            var anode = Net(graph, component, "A");
            var cathode = Net(graph, component, "K");
            return $"{ElementName(component.Reference, "B")} {anode} {cathode} I=IF(V({anode},{cathode})>0,V({anode},{cathode})/{SpiceText.Number(ideal.OnResistanceOhm)},V({anode},{cathode})/{SpiceText.Number(ideal.OffResistanceOhm)})";
        }
        var model = options.DiodeModel ?? throw new NotSupportedException("Diode export requires an explicit SpiceDiodeModelDefinition; no simulator-default diode model is assumed.");
        return $"{ElementName(component.Reference, "D")} {Net(graph, component, "A")} {Net(graph, component, "K")} {SpiceText.Identifier(model.Name, "CMD_DIODE")}";
    }

    private static string OpAmp(CircuitGraph graph, CircuitComponent component, CircuitSpiceExportOptions options)
    {
        if (component.Parameters.TryGetValue(ComponentParameterNames.OutputHighVoltage, out var high) &&
            component.Parameters.TryGetValue(ComponentParameterNames.OutputLowVoltage, out var low))
            return $"{ElementName(component.Reference, "B")} {Net(graph, component, "OUT")} 0 V=IF(V({Net(graph, component, "IN+")})>V({Net(graph, component, "IN-")}),{SpiceText.Number(high)},{SpiceText.Number(low)})";
        if (options.OpAmpMode == SpiceOpAmpExportMode.Unsupported)
            throw new NotSupportedException("The CircuitGraph contains an abstract op-amp, but no SPICE op-amp export strategy was selected.");
        if (options.OpAmpMode == SpiceOpAmpExportMode.FiniteGainVcvs)
            return $"{ElementName(component.Reference, "E")} {Net(graph, component, "OUT")} 0 {Net(graph, component, "IN+")} {Net(graph, component, "IN-")} {SpiceText.Number(options.OpAmpOpenLoopGain)}";

        var subcircuit = options.OpAmpSubcircuit ?? throw new InvalidOperationException("ExternalSubcircuit mode requires SpiceOpAmpSubcircuit options.");
        var pinMap = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            ["IN+"] = Net(graph, component, "IN+"), ["IN-"] = Net(graph, component, "IN-"), ["OUT"] = Net(graph, component, "OUT"),
            ["V+"] = Net(graph, component, "V+"), ["V-"] = Net(graph, component, "V-")
        };
        var nodes = subcircuit.PinOrder.Select(pin => pinMap.TryGetValue(pin, out var node) ? node : throw new InvalidOperationException($"Unsupported op-amp subcircuit pin '{pin}'. Use IN+, IN-, V+, V-, or OUT."));
        return $"{ElementName(component.Reference, "X")} {string.Join(' ', nodes)} {SpiceText.Identifier(subcircuit.Name, "CMD_OPAMP")}";
    }

    private static string Source(SpiceIndependentSource source)
    {
        var prefix = source.Kind == SpiceSourceKind.Voltage ? "V" : "I";
        var ac = source.AcMagnitude is { } magnitude ? $" AC {SpiceText.Number(magnitude)} {SpiceText.Number(source.AcPhaseDegrees)}" : string.Empty;
        return $"{ElementName(source.Name, prefix)} {SpiceText.Node(source.PositiveNode)} {SpiceText.Node(source.NegativeNode)} DC {SpiceText.Number(source.DcValue)}{ac}";
    }

    private static string Analysis(SpiceAnalysisDirective analysis) => analysis switch
    {
        SpiceAcAnalysis ac => $".AC {ac.Scale switch { SpiceSweepScale.Decade => "DEC", SpiceSweepScale.Octave => "OCT", _ => "LIN" }} {ac.PointCount} {SpiceText.Number(ac.StartFrequencyHz)} {SpiceText.Number(ac.StopFrequencyHz)}",
        SpiceDcAnalysis dc => $".DC {SpiceText.Identifier(dc.SourceName, "V1")} {SpiceText.Number(dc.StartValue)} {SpiceText.Number(dc.StopValue)} {SpiceText.Number(dc.Increment)}",
        SpiceTransientAnalysis transient => $".TRAN {SpiceText.Number(transient.TimeStepSeconds)} {SpiceText.Number(transient.StopTimeSeconds)} {SpiceText.Number(transient.StartSavingSeconds)}{(transient.MaximumTimeStepSeconds is { } maximum ? " " + SpiceText.Number(maximum) : string.Empty)}",
        SpiceOperatingPointAnalysis => ".OP",
        _ => throw new NotSupportedException($"No SPICE analysis mapping exists for {analysis.GetType().Name}.")
    };

    private static string AnalysisDomain(IReadOnlyList<SpiceAnalysisDirective> analyses) => analyses.FirstOrDefault() switch
    {
        SpiceAcAnalysis => "AC", SpiceDcAnalysis => "DC", SpiceTransientAnalysis => "TRAN", _ => "DC"
    };

    private static string Net(CircuitGraph graph, CircuitComponent component, string pinName)
    {
        var net = graph.GetNetForPin(component.GetPin(pinName)) ?? throw new InvalidOperationException($"{component.Reference}.{pinName} is not connected.");
        return SpiceText.Node(net.Name);
    }

    private static string ElementName(string reference, string prefix)
    {
        var safe = SpiceText.Identifier(reference, prefix + "1");
        return safe.StartsWith(prefix, StringComparison.OrdinalIgnoreCase) ? safe : prefix + "_" + safe;
    }

    private static void Validate(CircuitSpiceExportOptions options)
    {
        if (!(options.OpAmpOpenLoopGain > 0) || !double.IsFinite(options.OpAmpOpenLoopGain)) throw new ArgumentOutOfRangeException(nameof(options.OpAmpOpenLoopGain));
        if (options.SourceResistanceOhm is < 0 || options.LoadResistanceOhm is <= 0 || options.HighImpedanceOutputLoadOhm is <= 0) throw new ArgumentOutOfRangeException(nameof(options), "Termination resistances must be positive; source resistance may be zero/omitted.");
        if (options.Analyses.Count > 1) throw new ArgumentException("LTspice simulation netlists may contain only one active analysis directive; export alternatives as separate netlists.", nameof(options.Analyses));
        if (options.OutputExpressions.Count > 0 && options.Analyses.Count == 0) throw new ArgumentException(".PRINT expressions require an analysis directive.", nameof(options.OutputExpressions));
        foreach (var analysis in options.Analyses)
        {
            if (analysis is SpiceAcAnalysis ac && (!(ac.StartFrequencyHz > 0) || !(ac.StopFrequencyHz > ac.StartFrequencyHz) || ac.PointCount <= 0)) throw new ArgumentOutOfRangeException(nameof(options.Analyses), "Invalid AC sweep.");
            if (analysis is SpiceDcAnalysis dc && (dc.Increment == 0 || !double.IsFinite(dc.Increment))) throw new ArgumentOutOfRangeException(nameof(options.Analyses), "Invalid DC sweep increment.");
            if (analysis is SpiceTransientAnalysis transient && (!(transient.TimeStepSeconds > 0) || !(transient.StopTimeSeconds > 0))) throw new ArgumentOutOfRangeException(nameof(options.Analyses), "Invalid transient analysis.");
        }
        if (options.DiodeModel is { } diode && (!(diode.SaturationCurrentAmpere > 0) || !(diode.EmissionCoefficient > 0))) throw new ArgumentOutOfRangeException(nameof(options.DiodeModel));
        if (options.DiodeModel is not null && options.IdealDiodeModel is not null)
            throw new ArgumentException("Select either a Shockley diode model or a behavioral ideal-diode model, not both.", nameof(options));
        if (options.IdealDiodeModel is { } idealDiode &&
            (!(idealDiode.OnResistanceOhm > 0) || !(idealDiode.OffResistanceOhm > idealDiode.OnResistanceOhm) ||
             !double.IsFinite(idealDiode.OnResistanceOhm) || !double.IsFinite(idealDiode.OffResistanceOhm)))
            throw new ArgumentOutOfRangeException(nameof(options.IdealDiodeModel), "Ideal-diode Ron/Roff must be finite, positive, and ordered.");
    }

    private static void ValidateNodeMappings(CircuitGraph graph)
    {
        var collision = graph.Nets.GroupBy(net => SpiceText.Node(net.Name), StringComparer.OrdinalIgnoreCase).FirstOrDefault(group => group.Count() > 1);
        if (collision is not null)
            throw new InvalidOperationException($"SPICE node-name collision after normalization: {string.Join(", ", collision.Select(net => net.Name))} all map to {collision.Key}.");
    }

    private static int ComponentOrder(CircuitComponent component) => component.Type switch
    {
        ComponentType.Resistor => 0, ComponentType.Capacitor => 1, ComponentType.Inductor => 2, ComponentType.Diode => 3, ComponentType.OpAmp => 4,
        ComponentType.Comparator => 5, ComponentType.LogicGate => 6, _ => 9
    };

    private sealed class NaturalReferenceComparer : IComparer<string>
    {
        public static NaturalReferenceComparer Instance { get; } = new();
        public int Compare(string? first, string? second)
        {
            if (ReferenceEquals(first, second)) return 0; if (first == null) return -1; if (second == null) return 1;
            var firstPrefix = new string(first.TakeWhile(char.IsLetter).ToArray()); var secondPrefix = new string(second.TakeWhile(char.IsLetter).ToArray());
            var prefix = string.Compare(firstPrefix, secondPrefix, StringComparison.OrdinalIgnoreCase); if (prefix != 0) return prefix;
            return int.TryParse(first[firstPrefix.Length..], out var firstNumber) && int.TryParse(second[secondPrefix.Length..], out var secondNumber)
                ? firstNumber.CompareTo(secondNumber) : string.Compare(first, second, StringComparison.OrdinalIgnoreCase);
        }
    }
}
